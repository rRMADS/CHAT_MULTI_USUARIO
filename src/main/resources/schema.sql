CREATE TABLE IF NOT EXISTS reacao (
    mensagem_id BIGINT NOT NULL REFERENCES mensagem(id) ON DELETE CASCADE,
    participante VARCHAR(64) NOT NULL,
    emoji VARCHAR(8) NOT NULL,
    PRIMARY KEY (mensagem_id, participante, emoji)
);
